data class ImportContext(val config: Map<String, Any?>, val existing: List<Map<String, Any?>>)
class ExcelImportRepository(private val actor: PortalSession, private val db: FirebaseFirestore = FirebaseFirestore.getInstance()) {
    private val root get() = db.collection("schools").document(actor.schoolId)
    private suspend fun authorize() {
        check(actor.role == PortalRole.ADMIN && FirebaseAuth.getInstance().currentUser?.uid == actor.uid) { "Admin login required." }
        val user = db.collection("users").document(actor.uid).get(Source.SERVER).importAwait()
        check(user.getString("role") == "admin" && user.getString("schoolId") == actor.schoolId && user.getBoolean("active") == true && user.getBoolean("portalDisabled") != true) { "Active school Admin required." }
    }
    suspend fun context(role: String): ImportContext {
        authorize()
        val config = root.collection("academicConfig").document("current").get(Source.SERVER).importAwait()
        check(config.exists()) { "Configure the school's classes and academic session first." }
        val profiles = root.collection(if (role == "student") "students" else "teachers").get(Source.SERVER).importAwait()
        return ImportContext(config.data.orEmpty(), profiles.documents.map { it.data.orEmpty() + ("id" to it.id) })
    }
    suspend fun preview(role: String, sheet: List<List<String>>): ImportPreview {
        val context = context(role)
        return ImportPolicy.prepare(actor.schoolId, role, sheet, context.config, context.existing)
    }
    suspend fun template(role: String): ByteArray {
        val config = context(role).config
        val columns = ImportPolicy.columns(role)
        val classes = DiaryPolicy.maps(config["classes"]).filter { it["isActive"] == true }
        val sections = DiaryPolicy.maps(config["sections"]).filter { it["isActive"] == true }
        val reference = listOf(listOf("Class", "Section")) + sections.mapNotNull { sec -> classes.firstOrNull { it["id"] == sec["classId"] }?.let { listOf(it["name"].toString(), sec["name"].toString()) } }
        val instructions = listOf(listOf("Import Instructions"), listOf("Fill the first sheet; keep its column headings unchanged. Up to 100 people per file."),
            listOf("Registration and employee IDs, portal emails and passwords are generated by the app. All new profiles start Active."),
            listOf("Phone numbers and identity numbers must be text so their leading zeroes remain intact. Dates: YYYY-MM-DD text."),
            listOf("Do not use formulas. Paste values only. Leave optional fields blank."),
            listOf(if (role == "student") "Required: FullName, Gender (Male/Female), Class, Section, RollNo, FatherName, GuardianPhone, MonthlyFee. Use names from Class Reference." else "Required: FullName and Phone. Teacher phone numbers must be unique. Assign classes/subjects after import in Teachers & Assignments."),
            listOf("Preview errors must be corrected before importing. Save the login report after import."))
        return ExcelWorkbook.write(listOf((if (role == "student") "Students" else "Teachers") to (listOf(columns) + List(100) { List(columns.size) { "" } }), "Instructions" to instructions, "Class Reference" to reference))
    }
    suspend fun importRow(preview: ImportPreview, row: ImportRow): ImportResult {
        require(row.errors.isEmpty())
        authorize()
        val role = preview.role
        val ref = root.collection(if (role == "student") "students" else "teachers").document(row.id)
        val old = ref.get(Source.SERVER).importAwait()
        check(old.getBoolean("isDeleted") != true) { "This profile was removed; it cannot be restored by import." }
        if (old.exists()) check(ImportPolicy.key(old.getString(if (role == "student") "fullName" else "name").orEmpty()) == ImportPolicy.key(row.name)) { "This roll/phone belongs to another person. Refresh the preview." }
        val shortName = if (old.getString("portalEmail").isNullOrBlank()) {
            val school = root.get(Source.SERVER).importAwait()
            pk.edunexa.app.auth.StudentLoginIdentity.shortName(school.getString("settings.schoolShortName").orEmpty())
        } else ""
        val identifier = if (old.exists()) old.getString(if (role == "student") "admissionNo" else "employeeId").orEmpty().also { check(it.isNotBlank()) }
            else callback<String> { cb -> if (role == "student") RegistrationRepository(db).reserve(actor.schoolId, row.id, cb) else RegistrationRepository(db).reserveTeacher(actor.schoolId, row.id, cb) }
        if (!old.exists()) {
            if (role == "student") {
                val v = row.values
                val payload = mapOf<String, Any?>("id" to row.id, "fullName" to row.name, "admissionNo" to identifier, "rollNo" to v["RollNo"], "gender" to v["Gender"],
                    "classId" to v["classId"], "className" to v["Class"], "sectionId" to v["sectionId"], "section" to v["Section"], "academicSessionId" to preview.sessionId,
                    "fatherName" to v["FatherName"], "guardianPhone" to v["GuardianPhone"], "monthlyFee" to v["MonthlyFee"]!!.toDouble(),
                    "annualFund" to v["AnnualFund"].orEmpty().ifBlank { "0" }.toDouble(), "otherFunds" to v["OtherFunds"].orEmpty().ifBlank { "0" }.toDouble(),
                    "address" to v["Address"].orEmpty(), "admissionDate" to v["AdmissionDate"].orEmpty(), "dateOfBirth" to v["DateOfBirth"].orEmpty(), "bForm" to v["BForm"].orEmpty(),
                    "fatherCnic" to v["FatherCnic"].orEmpty(), "emergencyPhone" to v["EmergencyPhone"].orEmpty().ifBlank { v["GuardianPhone"].orEmpty() }, "fatherOccupation" to v["FatherOccupation"].orEmpty(),
                    "remarks" to v["Remarks"].orEmpty(), "status" to "Active", "isNewAdmission" to true, "concession" to "", "bloodGroup" to "")
                callback<Unit> { EnrollmentRepository(db).save(actor.schoolId, row.id, payload, it) }
            } else {
                val v = row.values
                val duplicates = root.collection("teachers").whereEqualTo("phone", v["Phone"]).get(Source.SERVER).importAwait()
                check(duplicates.documents.none { it.id != row.id && it.getBoolean("isDeleted") != true }) { "Teacher phone already exists. Refresh the preview." }
                callback<Unit> { TeacherDirectoryRepository(db).importTeacher(actor.schoolId, TeacherItem(id = row.id, name = row.name, employeeId = identifier, phone = v["Phone"].orEmpty(), email = v["ContactEmail"].orEmpty(), qualification = v["Qualification"].orEmpty(), joiningDate = v["JoiningDate"].orEmpty()), it) }
            }
        }
        val storedEmail = old.getString("portalEmail").orEmpty()
        val login = if (storedEmail.isNotBlank()) pk.edunexa.app.auth.GeneratedLogin(storedEmail,
            LoginGenerator.password(role, actor.schoolId, row.id, identifier, row.name))
        else LoginGenerator.generate(role, actor.schoolId, row.id, identifier, row.name, shortName)
        callback<Unit> { ProfileLoginRepository(db).create(actor.schoolId, role, row.id, login, it) }
        return ImportResult(row.number, row.name, identifier, login.email, login.password)
    }
}
private suspend fun <T> Task<T>.importAwait(): T = suspendCancellableCoroutine { c -> addOnSuccessListener { if(c.isActive) c.resume(it) }; addOnFailureListener { if(c.isActive) c.resumeWithException(it) } }
private suspend fun <T> callback(start: ((Result<T>) -> Unit) -> Unit): T = suspendCancellableCoroutine { c -> start { result -> if(c.isActive) result.fold({ c.resume(it) }, { c.resumeWithException(it) }) } }
